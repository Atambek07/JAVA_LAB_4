CREATE TABLE users(
    id   BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    age INT,
    inn BIGINT NOT NULL UNIQUE check ( inn >= 10000000000000 and inn <= 99999999999999 )
);

